import {formatBookingDate} from '../../src/lib/travel-date';
import {chooseFlightFilter,toggleResultSearch, test,expect,departure,searchId,flight} from './fixtures';

test('reopening the same AI card reapplies its view without reloading the owned search or undoing native filter edits',async({page,provider})=>{
  const direct=flight('ONWARD','indigo-direct'),other=flight('ONWARD','other-direct'),connecting=flight('ONWARD','indigo-connecting');
  other.sI[0].fD.aI={name:'Other Air',code:'ZZ'};
  connecting.sI=[{...connecting.sI[0],aa:{code:'HYD',city:'Hyderabad'}},{...connecting.sI[0],da:{code:'HYD',city:'Hyderabad'},dt:`${departure}T12:00:00`,at:`${departure}T14:00:00`}];
  const href=`/book?product=FLIGHT&flightSearch=${searchId}&flightStops=0&flightAirlineQuery=IndiGo&flightSort=departure`;
  provider.overrides['POST /api/travel/flight-search-snapshot']={body:{searchId,expiresAt:new Date(Date.now()+600_000).toISOString(),criteria:{product:'FLIGHT',from:'BOM',to:'DEL',date:departure,adults:'1',children:'0',infants:'0',cabin:'ECONOMY'},results:{searchResult:{tripInfos:{ONWARD:[connecting,other,direct]}}}}};
  provider.overrides['POST /api/travel/max-ai']={body:{reply:'Reopen your checked non-stop IndiGo results.',cards:[{id:'same-owned-result',type:'flight',title:'IndiGo result',subtitle:'BOM → DEL',details:[],action:{label:'Reopen checked flights',href}}],actions:[],conversationToken:'synthetic-token'}};
  await page.goto(href);
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toHaveCount(1);
  const sorts=page.getByRole('group',{name:'Sort flights',exact:true});
  const selectedSort=sorts.getByRole('button',{pressed:true});
  const nonstop=page.getByRole('button',{name:'Non-stop',exact:true});
  await page.getByRole('button',{name:'Remove airline preference IndiGo',exact:true}).click();
  await expect(nonstop).toHaveAttribute('aria-pressed','true');
  await nonstop.press('Enter');
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toHaveCount(3);
  await sorts.getByRole('button',{name:'Cheapest',exact:true}).click();
  const filters=page.getByRole('button',{name:/^Filters(?: \(\d+\))?$/});
  if(await filters.isVisible())await filters.click();
  await chooseFlightFilter(page,'Airline (any segment)','Other Air');
  const close=page.getByRole('button',{name:'Close filters',exact:true});if(await close.isVisible())await close.click();
  await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))));
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toHaveCount(1);
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toContainText('Other Air');
  await expect(selectedSort).toHaveAccessibleName('Cheapest');
  await page.getByRole('button',{name:'Open Max AI travel assistant',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'Max AI',exact:true});
  await panel.getByRole('textbox',{name:'Your message to Max AI',exact:true}).fill('Reopen those flights');
  await panel.getByRole('button',{name:'Send message to Max AI',exact:true}).click();
  await panel.getByRole('link',{name:'Reopen checked flights',exact:true}).click();
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toHaveCount(1);
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toContainText('IndiGo');
  await expect(page.getByRole('button',{name:'Remove airline preference IndiGo',exact:true})).toBeVisible();
  await expect(nonstop).toHaveAttribute('aria-pressed','true');
  await expect(selectedSort).toHaveAccessibleName('Earliest departure');
  expect(provider.requests('/api/travel/flight-search-snapshot')).toHaveLength(1);
  expect(provider.requests('/api/travel/search')).toHaveLength(0);
  expect(provider.requests('/api/travel/review')).toHaveLength(0);
  expect(provider.requests('/api/payments/create')).toHaveLength(0);
});

test('an original AI card restores its own inventory after an explicit different manual search',async({page,provider})=>{
  const original=flight('ONWARD','original-fare'),newer=flight('ONWARD','newer-fare');
  newer.sI[0].fD.aI={name:'New search airline',code:'ZZ'};
  const newerId='11111111-1111-4111-8111-111111111119',changed=new Date(`${departure}T00:00:00Z`);changed.setUTCDate(changed.getUTCDate()+1);const newerDate=changed.toISOString().slice(0,10);
  const href=`/book?product=FLIGHT&flightSearch=${searchId}&flightStops=0&flightAirlineQuery=IndiGo`;
  provider.overrides['POST /api/travel/flight-search-snapshot']={body:{searchId,expiresAt:new Date(Date.now()+600_000).toISOString(),criteria:{product:'FLIGHT',from:'BOM',to:'DEL',date:departure,adults:'1',children:'0',infants:'0',cabin:'ECONOMY'},results:{searchResult:{tripInfos:{ONWARD:[original]}}}}};
  provider.overrides['POST /api/travel/max-ai']={body:{reply:'Your original checked flight.',cards:[],actions:[{label:'Reopen original flight search',href}],conversationToken:'synthetic-token'}};
  provider.search={searchId:newerId,results:{searchResult:{tripInfos:{ONWARD:[newer]}}}};
  await page.goto(href);
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toContainText('IndiGo');
  await toggleResultSearch(page);
  await page.getByLabel('Departure',{exact:true}).fill(newerDate);
  await page.getByRole('button',{name:'Search flights',exact:true}).click();
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toContainText('New search airline');
  await expect(page).not.toHaveURL(/flightSearch=/);
  await page.getByRole('button',{name:'Open Max AI travel assistant',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'Max AI',exact:true});
  await panel.getByRole('textbox',{name:'Your message to Max AI',exact:true}).fill('Show my original flight search');
  await panel.getByRole('button',{name:'Send message to Max AI',exact:true}).click();
  await panel.getByRole('link',{name:'Reopen original flight search',exact:true}).click();
  await expect(page.locator('.flight-shopping-list .live-flight-card')).toContainText('IndiGo');
  await expect(page.locator('.flight-shopping-list .live-flight-card')).not.toContainText('New search airline');
  await toggleResultSearch(page);
  await expect(page.getByLabel('Departure',{exact:true})).toHaveValue(formatBookingDate(departure));
  expect(provider.requests('/api/travel/flight-search-snapshot')).toHaveLength(2);
  expect(provider.requests('/api/travel/search')).toHaveLength(1);
  expect(provider.requests('/api/travel/search')[0].body).toMatchObject({date:newerDate});
  expect(provider.requests('/api/travel/review')).toHaveLength(0);
  expect(provider.requests('/api/payments/create')).toHaveLength(0);
});
